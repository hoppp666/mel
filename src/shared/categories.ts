export function getCategoriesForCollection(
  collection: CollectionType,
  customCategories?: { debate: string[]; romantic: string[] }
): string[] {
  const base = collection === 'debate' ? DEBATE_CATEGORIES : ROMANTIC_CATEGORIES;
  const extra = customCategories ? customCategories[collection] : [];
  return Array.from(new Set([...base, ...extra]));
}
