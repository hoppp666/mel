export function buildDebateSeeds(): StoryPlot[] {
  const baseDate = new Date('2026-11-10T10:00:00.000Z').getTime();
  return RAW_DEBATE_SEEDS.map((seed, idx) => {
    const overall = seed.overallTarget ?? 90 + (idx % 5);
    const quality = calculateQualityScore(
      'debate',
      {
        originality: overall - 1,
        realism: overall + 2,
        emotionalDepth: overall,
        engagement: overall + 1,
        discussionPotential: overall + 3,
        specificity: overall + 1,
        variability: overall - 2,
        ambiguity: overall + 2,
        bothSidesStrength: overall,
        contradictionPower: overall + 1,
      },
      seed.verificationStatus === 'needs_revision'
        ? 'Сильная деталь прошлого вклада мужа, но стоит уточнить диалог на следующий день для большей неоднозначности.'
        : 'Живая узнаваемая дилемма с сильными аргументами обеих сторон и яркой скрытой деталью.'
    );

    const story: StoryPlot = {
      id: seed.id,
      collection: 'debate',
      category: seed.category,
      subcategory: seed.subcategory,
      title: seed.title,
      shortDescription: seed.shortDescription,
      fullPlot: seed.fullPlot,
      participants: seed.participants,
      setting: seed.setting,
      coreConflictOrAction: seed.coreConflictOrAction,
      sideAPosition: seed.sideAPosition,
      sideBPosition: seed.sideBPosition,
      emotionalMechanism: seed.emotionalMechanism,
      hiddenExpectation: seed.hiddenExpectation,
      unexpectedNuance: seed.unexpectedNuance,
      possibleTwist: seed.possibleTwist,
      mainTriggerQuestion: seed.mainTriggerQuestion,
      additionalQuestions: seed.additionalQuestions,
      keywords: seed.keywords,
      ideaSource: 'Оригинальная редакционная разработка MELO_LOVE (Партия #1)',
      sourceUrl: '',
      originType: 'original',
      createdAt: new Date(baseDate + idx * 3600_000).toISOString(),
      verificationStatus: seed.verificationStatus || 'approved',
      usageStatus: 'unused',
      semanticFingerprint: '',
      mainTheme: seed.mainTheme,
      plotMechanic: seed.plotMechanic,
      uniqueDetails: seed.uniqueDetails,
      sourceAnalysisNote: 'Сформировано на этапе стартового наполнения коллекции «Кто здесь прав?» без внешних заимствований.',
      batchNumber: 1,
      quality,
      similarityMatches: [],
      duplicateFlag: false,
    };
    story.semanticFingerprint = buildSemanticFingerprint(story);
    return story;
  });
}
